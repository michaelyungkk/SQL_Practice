const createLessonContent = (
  summary: string,
  theory: string,
  pattern: string,
  exampleWalkthrough: string,
  keyTakeaway: string,
): LessonContent => ({
  summary,
  theory,
  pattern,
  exampleWalkthrough,
  keyTakeaway,
})

const buildChallenge = (challenge: Challenge): Challenge => ({
  ...challenge,
  lessonContent:
    challenge.mode === 'learn'
      ? challenge.lessonContent ??
        createLessonContent(
          `This lesson introduces ${challenge.concept} through a small analyst task.`,
          `${challenge.explanation} ${challenge.analystUseCase}`,
          `Start with the table you need, then add the ${challenge.concept} pattern that changes the output in the way the business question needs.`,
          `Read the example query line by line. Notice how the SQL keyword matches the business request before you try the exercise yourself.`,
          challenge.followUp ?? 'Once the result looks right, try changing one piece of the query and observe how the output changes.',
        )
      : challenge.lessonContent,
})

